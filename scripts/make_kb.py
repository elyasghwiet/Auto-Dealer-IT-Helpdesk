os.makedirs(OUT, exist_ok=True)
index = ["# Knowledge Base - EV Fleet Operator IT Service Desk", "",
         "Simple articles for employees and support staff. Screenshot placeholders are marked **[SCREENSHOT]**.", "",
         "| ID | Title | Category |", "|---|---|---|"]
out_json = []
for i, a in enumerate(A, 1):
    kid = "KB-%02d" % i
    slug = re.sub(r"[^a-z0-9]+", "-", a["title"].lower()).strip("-")[:50]
    fn = "%s-%s.md" % (kid, slug)
    md = ["# %s: %s" % (kid, a["title"]), "",
          "**Category:** %s  |  **Applies to:** %s" % (a["category"], a["applies"]), "",
          "## The problem", a["problem"], "", "## Fix it yourself"]
    md += ["%d. %s" % (n, s) for n, s in enumerate(a["steps"], 1)]
    md += ["", "**[SCREENSHOT]** %s" % a["shot"], "", "## Still not working?", a["still"], "",
           "## How to avoid it", a["prevent"], "", "## Open a ticket", "Category and priority: %s" % a["ticket"], ""]
    open(os.path.join(OUT, fn), "w", encoding="utf-8").write("\n".join(md))
    index.append("| %s | [%s](%s) | %s |" % (kid, a["title"], fn, a["category"]))
    out_json.append(dict(id=kid, file=fn, **a))
open(os.path.join(OUT, "INDEX.md"), "w", encoding="utf-8").write("\n".join(index) + "\n")
json.dump(out_json, open(os.path.join(OUT, "articles.json"), "w"), indent=1)
print(len(A), "articles written to", OUT)
